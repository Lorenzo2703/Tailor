-- Source: ISTAT municipality codes and IndicePA data as republished by opendatasicilia/comuni-italiani
-- (coordinates are the town hall centroid, EPSG:4326). Only Lazio (pilot region) is loaded: add more regions
-- with a new migration. TO BE VERIFIED: attribution/license terms of the upstream dataset before launch.

create function public.slugify(input text)
returns text
language sql
immutable
set search_path = ''
as $$
  select trim(both '-' from regexp_replace(
    translate(lower(input), 'àáâäèéêëìíîïòóôöùúûüçñ', 'aaaaeeeeiiiioooouuuucn'),
    '[^a-z0-9]+', '-', 'g'));
$$;

grant execute on function public.slugify(text) to anon, authenticated;

create table public.italian_cities (
  istat_code text primary key,
  name text not null,
  slug text generated always as (public.slugify(name)) stored unique,
  province text not null,
  province_code text not null,
  region text not null,
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180)
);

alter table public.italian_cities enable row level security;
grant select on public.italian_cities to anon, authenticated;

create policy italian_cities_select on public.italian_cities for select to anon, authenticated
  using (true);

